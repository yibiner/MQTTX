import store from '@/store'
import useServices from '@/database/useServices'
import time from '@/utils/time'
import { ignoreQoS0Message } from '@/utils/mqttUtils'
import { DEFAULT_HISTORY_MAX_COUNT } from '@/utils/data'

/**
 * Looks for an already stored history record matching the given one.
 *
 * @param data the record about to be saved (topic + optional message)
 * @param matchMessage when true a record only matches if it carries the very same message,
 *                     when false only the topic/QoS/retain part is compared (used when the user
 *                     disabled "save message together").
 */
/**
 * How a published body should be stored.
 *
 * A JSON object or array is marked JSON so the history viewer formats it. Anything else,
 * including a payload that only looks a little like JSON, stays plaintext: the history then
 * shows the characters that were published.
 */
export const publishedPayloadType = (payload: string | Buffer | undefined | null): PayloadType => {
  const text = payload === undefined || payload === null ? '' : String(payload).trim()
  const wrapped = (text.startsWith('{') && text.endsWith('}')) || (text.startsWith('[') && text.endsWith(']'))
  if (!wrapped) {
    return 'Plaintext'
  }
  try {
    JSON.parse(text)
    return 'JSON'
  } catch (error) {
    return 'Plaintext'
  }
}

export const hasMessageHeaderID = async (
  data: HistoryMessageHeaderModel,
  matchMessage = true,
): Promise<string | null> => {
  const { historyMessageHeaderService } = useServices()
  // The lookup runs in SQL: loading the whole history (payloads included) on every publish was
  // the hot path for timed messages.
  return await historyMessageHeaderService.findMatchingId(data, matchMessage)
}

export default {}

/**
 * Records a message that was published without the connection view.
 *
 * Mirrors what the view's publish pipeline stores: the publish history keeps the topic as it was
 * written (so the existing entry for that topic is bumped instead of duplicated), while the message
 * list entry keeps the topic that really went on the wire. Used by the timed messages and by the
 * automatic replies, both of which can publish while another page is open.
 */
export const savePublishedMessageHistory = async (
  connectionId: string,
  template: {
    /** message id, generated by the caller so the row and the history share it */
    id?: string
    topic: string
    qos: QoS
    retain: boolean
    /** the payload as the user configured it, i.e. the template of a timed message */
    payload?: string
  },
  publishedPayload: string | Buffer | undefined,
  type: PayloadType,
  wireTopic: string,
): Promise<void> => {
  const appState = (store.state as any).app ?? {}
  const saveHistoryMessage: boolean = appState.saveHistoryMessage ?? true
  const { historyMessageHeaderService, messageService } = useServices()
  const header: HistoryMessageHeaderModel = {
    connectionId,
    qos: template.qos,
    retain: template.retain,
    topic: template.topic,
    ...(saveHistoryMessage ? { payload: template.payload, payloadType: type } : {}),
  }
  const recordIdToUpdate = await hasMessageHeaderID(header, saveHistoryMessage)
  recordIdToUpdate
    ? await historyMessageHeaderService.updateCreateAt(recordIdToUpdate)
    : await historyMessageHeaderService.create(header)
  await historyMessageHeaderService.trim(appState.historyMaxCount ?? DEFAULT_HISTORY_MAX_COUNT)
  if (publishedPayload === undefined || publishedPayload === '' || ignoreQoS0Message(template.qos)) {
    return
  }
  await messageService.pushMsgsToConnection(
    [
      {
        id: template.id,
        out: true,
        createAt: time.getNowDate(),
        // the message list shows what went on the wire, the topic template stays in the history
        topic: wireTopic,
        payload: publishedPayload.toString(),
        qos: template.qos,
        retain: template.retain,
      },
    ],
    connectionId,
  )
}
